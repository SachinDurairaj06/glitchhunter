let frame = 0;
let alive = true;

function setCamera(spec) {
  const s = { ...DEFAULT_CAM, ...(spec || {}) };
  cameraMode = 'free';
  camera.position.set(s.pos[0], s.pos[1], s.pos[2]);
  camTarget.set(s.target[0], s.target[1], s.target[2]);
  camera.fov = s.fov;
  camera.updateProjectionMatrix();
  camera.lookAt(camTarget);
}

function cameraSpec() {
  return { pos: camera.position.toArray(), target: camTarget.toArray(), fov: camera.fov, mode: cameraMode };
}

function renderFrame() {
  //#if shimmer
  camera.updateMatrixWorld();
  updateHaze();
  //#endif
  renderer.clear();
  //#if bloom
  composer.render();
  //#endif
  //#if !bloom
  renderer.render(scene, camera);
  //#endif
  //#if hud
  renderer.clearDepth();
  renderer.render(hudScene, hudCam);
  //#endif
}

function tick() {
  if (!alive) return; // an uncaught error stops the loop, like a dead requestAnimationFrame chain
  try {
    frame += 1;
    //#if conveyor
    updateConveyor();
    //#endif
    //#if robot
    updateRobot();
    //#endif
    //#if bloom
    furnaceLight.intensity = 7 * (0.9 + 0.1 * Math.sin(frame * 0.31) * Math.sin(frame * 0.07 + 0.4));
    //#endif
    //#if sparks
    updateSparks();
    //#endif
    //#if chute
    stepPhysics();
    //#endif
    //#if crate_stack
    updateStack();
    //#endif
    //#if drone
    updateDrone();
    updateFollowCam();
    //#endif
    //#if telemetry
    telemetry.frames += 1;
    //#endif
    renderFrame();
    //#if telemetry
    telemetry.drawCalls = renderer.info.render.calls;
    //#endif
  } catch (e) {
    alive = false;
    errors.push({ type: 'exception', message: String((e && e.message) || e), frame });
  }
}

function setKey(code, down) {
  if (down && !keys.has(code)) {
    //#if chute
    if (code === 'KeyE') dropCrateNow();
    //#endif
    //#if drone
    if (code === 'KeyF') {
      if (cameraMode === 'follow') setCamera(DEFAULT_CAM);
      else enterFollow();
    }
    //#endif
    //#if inventory
    if (code === 'KeyI') toggleInventory();
    //#endif
  }
  if (down) keys.add(code);
  else keys.delete(code);
}

function pick(x, y) {
  const ndc = new THREE.Vector2((x / W) * 2 - 1, -(y / H) * 2 + 1);
  const ray = new THREE.Raycaster();
  ray.setFromCamera(ndc, camera);
  const hits = ray.intersectObjects(scene.children, true)
    .filter((h) => h.object.visible && (h.object.isMesh || h.object.isInstancedMesh) && !h.object.isPoints);
  if (!hits.length) return { hit: false };
  const h = hits[0];
  // Surfaces at (almost) the same depth as the first hit: a strong hint for z-fighting.
  const coplanar = [...new Set(hits
    .filter((o) => Math.abs(o.distance - h.distance) < 0.005)
    .map((o) => o.object.name || 'unnamed'))];
  return { hit: true, point: h.point.toArray(), object: h.object.name || 'unnamed', distance: h.distance, coplanar };
}

