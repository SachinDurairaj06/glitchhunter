// --- heat haze over the furnace: a screen-space post pass in the HDR chain ----------------------
const hazeCorners = [[-7.3, 1.6], [-4.7, 1.6], [-7.3, 3.5], [-4.7, 3.5]].map(([x, y]) => new THREE.Vector3(x, y, -6.6));
const hazePass = new ShaderPass({
  uniforms: { tDiffuse: { value: null }, uTime: { value: 0 }, uRect: { value: new THREE.Vector4(2, 2, 3, 3) } },
  vertexShader: `
    varying vec2 vUv;
    void main() {
      vUv = uv;
      gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
    }`,
  fragmentShader: `
    uniform sampler2D tDiffuse;
    uniform float uTime;
    uniform vec4 uRect;
    varying vec2 vUv;
    void main() {
      vec4 color = texture2D(tDiffuse, vUv);
      vec2 local = (vUv - uRect.xy) / (uRect.zw - uRect.xy);
      if (local.x > 0.0 && local.x < 1.0 && local.y > 0.0 && local.y < 1.0) {
        float n = sin(local.x * 17.0 + uTime * 2.6) * sin(local.y * 9.0 - uTime * 3.1);
        float heat = pow(max(n, 0.0), 1.5); //#var nan: float heat = n * sqrt(n); // same falloff, cheaper than pow
        float edge = smoothstep(0.0, 0.3, local.y) * smoothstep(1.0, 0.55, local.y)
                   * smoothstep(0.0, 0.25, local.x) * smoothstep(1.0, 0.75, local.x);
        color.rgb += vec3(0.9, 0.45, 0.15) * heat * edge;
      }
      gl_FragColor = color;
    }`,
});
composer.insertPass(hazePass, 2);

function updateHaze() {
  // Screen rectangle (in UV) of the hot air above the furnace mouth, for the post pass.
  let x0 = 2;
  let y0 = 2;
  let x1 = -2;
  let y1 = -2;
  for (const c of hazeCorners) {
    const p = c.clone().applyMatrix4(camera.matrixWorldInverse);
    if (p.z > -camera.near) {
      hazePass.uniforms.uRect.value.set(2, 2, 3, 3); // behind the camera: no haze
      return;
    }
    p.applyMatrix4(camera.projectionMatrix);
    x0 = Math.min(x0, p.x * 0.5 + 0.5);
    x1 = Math.max(x1, p.x * 0.5 + 0.5);
    y0 = Math.min(y0, p.y * 0.5 + 0.5);
    y1 = Math.max(y1, p.y * 0.5 + 0.5);
  }
  hazePass.uniforms.uRect.value.set(x0, y0, x1, y1);
  hazePass.uniforms.uTime.value = frame * DT;
}
