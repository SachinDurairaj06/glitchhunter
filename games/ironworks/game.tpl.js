function stepPhysics() {
  if (!drop.active) return;
  if (drop.rest !== null) {
    settle(drop);
  } else {
    const h = DT / PHYS_SUBSTEPS;
    for (let i = 0; i < PHYS_SUBSTEPS; i++) {
      drop.vy -= 9.8 * h;
      drop.y += drop.vy * h;
      const bottom = drop.y - HALF;
      if (bottom <= SHELF_Y + 0.06 && bottom >= SHELF_Y - 0.08) {
        drop.rest = SHELF_Y + 0.06 + HALF; // landed on the shelf
        break;
      }
      if (bottom <= 0) {
        drop.rest = HALF; // on the ground
        drop.y = Math.max(drop.y, HALF - 0.05);
        break;
      }
    }
  }
  dropCrate.position.y = drop.y;
}
