function makeMissingTexture() {
  // Engine-style placeholder: a magenta/black checker shown when an asset fails to load.
  const size = 8;
  const data = new Uint8Array(size * size * 4);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const i = (y * size + x) * 4;
      const on = (x + y) % 2 === 0;
      data[i] = on ? 255 : 0;
      data[i + 1] = 0;
      data[i + 2] = on ? 255 : 0;
      data[i + 3] = 255;
    }
  }
  const tex = new THREE.DataTexture(data, size, size);
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = THREE.NearestFilter;
  tex.colorSpace = THREE.SRGBColorSpace;
  tex.needsUpdate = true;
  return tex;
}

function loadTex(url, material, repeat, onDone) {
  loading += 1;
  loader.load(
    url,
    (tex) => {
      tex.colorSpace = THREE.SRGBColorSpace;
      tex.anisotropy = 4;
      if (repeat) {
        tex.wrapS = THREE.RepeatWrapping;
        tex.wrapT = THREE.RepeatWrapping;
        tex.repeat.set(repeat[0], repeat[1]);
      }
      material.map = tex;
      material.needsUpdate = true;
      if (onDone) onDone(tex);
      loading -= 1;
    },
    undefined,
    () => {
      errors.push({ type: 'asset_missing', url });
      material.map = MISSING;
      material.needsUpdate = true;
      loading -= 1;
    },
  );
}

