function walkClip() {
  // Authored against the original bone names (as exported from the animation tool).
  const t = [0, 0.25, 0.5, 0.75, 1.0];
  const qx = (a) => new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(1, 0, 0), a);
  const qz = (a) => new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0, 0, 1), a);
  const track = (name, quats) => new THREE.QuaternionKeyframeTrack(`${name}.quaternion`, t,
    quats.flatMap((q) => q.toArray()));
  const swing = (amp) => [amp, 0, -amp, 0, amp];
  const arm = (side, amp) => swing(amp).map((a) => qx(a).multiply(qz(side * 1.25)));
  return new THREE.AnimationClip('walk', 1.0, [
    new THREE.VectorKeyframeTrack('hips.position', t, [0, 1.0, 0, 0, 0.955, 0, 0, 1.0, 0, 0, 0.955, 0, 0, 1.0, 0]),
    track('thighL', swing(-0.45).map(qx)),
    track('thighR', swing(0.45).map(qx)),
    track('shinL', [0.15, 0.05, 0.15, 0.75, 0.15].map(qx)),
    track('shinR', [0.15, 0.75, 0.15, 0.05, 0.15].map(qx)),
    track('armL', arm(-1, 0.4)),
    track('armR', arm(1, -0.4)),
  ]);
}

